import fs from "node:fs";
import path from "node:path";
import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  // Main address is https://cascadecharterbus.com (no www); trailing-slash URLs everywhere.
  trailingSlash: true,
  poweredByHeader: false,
  reactStrictMode: true,
  headers() {
    return Promise.resolve([
      { source: "/images/:path*", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
      { source: "/hero-bus.webp", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
      { source: "/hero-bus.jpg", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
      { source: "/logo.png", headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }] },
    ]);
  },
  images: {
    minimumCacheTTL: 31536000,
    formats: ["image/avif", "image/webp"],
  },
  // Redirect/410 rules are generated by scripts/build-redirects into `redirects.json`
  // and imported here (brief Sections 9.1 and 10). Populated in Phase 6.
  async redirects() {
    const base = [
      // One main address: every www -> apex (https handled by host)
      { source: "/:path*", has: [{ type: "host", value: "www.cascadecharterbus.com" }], destination: "https://cascadecharterbus.com/:path*", permanent: true },
    ];
    let removed: Array<{ source: string; destination: string; permanent: boolean }> = [];
    // Build-time redirects stay for the generated 410/removed-city set only.
    // NOTE (Admin Panel Upgrade Phase 4): admin-managed rules moved OUT of the
    // build — they are applied live at runtime by middleware.ts (node runtime),
    // so a saved rule is live in seconds with no deploy.
    try {
      removed = JSON.parse(
        await fs.promises.readFile(
          path.join(process.cwd(), "redirects-generated.json"),
          "utf8"
        )
      );
    } catch {
      removed = [] as Array<{ source: string; destination: string; permanent: boolean }>;
      // removed initialized above
    }
    const all: Array<{ source: string; destination: string; permanent: boolean }> = [...base, ...removed];
    return all as any;
  },
};

export default nextConfig;
