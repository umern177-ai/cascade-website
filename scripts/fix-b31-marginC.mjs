import { readFileSync, writeFileSync } from "node:fs";
const path = "data/city-pages.json";
const data = JSON.parse(readFileSync(path, "utf8"));
const get = (st, sl) => data.find((c) => c.state === st && c.slug === sl);
const add = (st, sl, key, val) => {
  const e = get(st, sl);
  if (!e) return;
  if (key === "h") e.heroIntro += " " + val;
  else if (key === "s0") e.services[0].text += " " + val;
  else if (key === "s1") e.services[1].text += " " + val;
  else if (key === "s2") e.services[2].text += " " + val;
  else if (key === "d0") e.destinations[0].text += " " + val;
  else if (key === "d1") e.destinations[1].text += " " + val;
  else if (key === "d2") e.destinations[2].text += " " + val;
  else if (key === "f0") e.faqs[0].a += " " + val;
  else if (key === "f1") e.faqs[1].a += " " + val;
  else if (key === "f2") e.faqs[2].a += " " + val;
  else if (key === "f3") e.faqs[3].a += " " + val;
  else if (key === "l") e.premium.heroLead += ", with " + val;
};

